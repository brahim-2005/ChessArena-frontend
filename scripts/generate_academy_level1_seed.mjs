import fs from 'node:fs';
import path from 'node:path';
import { createRequire, Module } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ts = require('typescript');

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function loadTypeScript(filePath) {
  const source = fs.readFileSync(filePath, 'utf8');
  const output = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
      esModuleInterop: true,
    },
  }).outputText;
  const loaded = new Module(filePath);
  loaded.filename = filePath;
  loaded.paths = Module._nodeModulePaths(path.dirname(filePath));
  loaded._compile(output, filePath);
  return loaded.exports;
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlJson(value) {
  return `${sqlString(JSON.stringify(value))}::jsonb`;
}

const { getLevel1Lessons, getLevel1Quiz } = loadTypeScript(
  path.join(root, 'src', 'lib', 'learning', 'level1.ts')
);
const { validateAcademyQuiz } = loadTypeScript(
  path.join(root, 'src', 'lib', 'learning', 'academy.ts')
);

const statements = [
  '-- Generated by scripts/generate_academy_level1_seed.js. Apply sql/academy.sql first.',
  'BEGIN;',
];

for (const lesson of getLevel1Lessons()) {
  const { id, levelNumber, lessonNumber, title, summary, ...content } = lesson;
  statements.push(
    `INSERT INTO public.academy_lessons (id, level_number, lesson_number, title, summary, content, published) VALUES (` +
    `${sqlString(id)}, ${levelNumber}, ${lessonNumber}, ${sqlJson(title)}, ${sqlJson(summary)}, ${sqlJson(content)}, TRUE` +
    `) ON CONFLICT (id) DO UPDATE SET level_number = EXCLUDED.level_number, ` +
    `lesson_number = EXCLUDED.lesson_number, title = EXCLUDED.title, summary = EXCLUDED.summary, ` +
    `content = EXCLUDED.content, published = TRUE, updated_at = NOW();`
  );

  const questions = getLevel1Quiz(id);
  const errors = validateAcademyQuiz(questions);
  if (errors.length > 0) {
    throw new Error(`${id} is not valid:\n${errors.join('\n')}`);
  }
  for (const question of questions) {
    statements.push(
      `INSERT INTO public.academy_questions (` +
      `id, lesson_id, question_number, difficulty, question_type, prompt, choices, correct_answer, ` +
      `explanation, hint, fen, solution_moves` +
      `) VALUES (` +
      `${sqlString(question.id)}, ${sqlString(id)}, ${question.questionNumber}, ` +
      `${sqlString(question.difficulty)}, ${sqlString(question.type)}, ${sqlJson(question.prompt)}, ` +
      `${sqlJson(question.choices)}, ${sqlString(question.correctAnswer)}, ${sqlJson(question.explanation)}, ` +
      `${sqlJson(question.hint ?? {})}, ${question.fen ? sqlString(question.fen) : 'NULL'}, ` +
      `${sqlJson(question.solutionMoves ?? [])}` +
      `) ON CONFLICT (id) DO UPDATE SET lesson_id = EXCLUDED.lesson_id, ` +
      `question_number = EXCLUDED.question_number, difficulty = EXCLUDED.difficulty, ` +
      `question_type = EXCLUDED.question_type, prompt = EXCLUDED.prompt, choices = EXCLUDED.choices, ` +
      `correct_answer = EXCLUDED.correct_answer, explanation = EXCLUDED.explanation, hint = EXCLUDED.hint, ` +
      `fen = EXCLUDED.fen, solution_moves = EXCLUDED.solution_moves;`
    );
  }
}

statements.push('COMMIT;');
const outputPath = path.join(root, 'sql', 'academy_level1_seed.sql');
fs.writeFileSync(outputPath, `${statements.join('\n')}\n`, 'utf8');
console.log(`Generated ${outputPath} with 10 lessons and 200 validated questions.`);
